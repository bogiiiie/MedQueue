// DOWNLOAD QUEUE CARD (PDF)
// ============================================================
function downloadQueueCard() {
  if (typeof window.jspdf === 'undefined') {
    alert('PDF download is not available yet.');
    return;
  }

  const queueNumber = currentData.queue_number || '—';
  const patientName = currentData.patient_name || 'Patient';
  const department = currentData.department || '—';
  const counter = currentData.counter || '—';
  const position = currentData.position || 0;
  const estimatedWait = currentData.estimated_wait || '—';
  const email = currentData.email || '—';
  const [u, d] = email.includes('@') ? email.split('@') : ['—', ''];
  const maskedEmail = email !== '—' ? u.slice(0, 2) + '***@' + d : '—';

  const now = new Date();
  const generatedDate = now.toLocaleDateString('en-PH');
  const generatedAt = now.toLocaleTimeString('en-PH', { hour: '2-digit', minute: '2-digit' });

  const { jsPDF } = window.jspdf;
  const W = 105, H = 175;
  const doc = new jsPDF({ unit: 'mm', format: [W, H] });

  // Header
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(0);
  doc.text('MedQueue', W / 2, 14, { align: 'center' });

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(130);
  doc.text('HOSPITAL QUEUEING SYSTEM', W / 2, 20, { align: 'center' });

  // Queue number
  doc.setFontSize(42);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(0, 102, 255);
  doc.text(queueNumber, W / 2, 38, { align: 'center' });

  // Divider
  doc.setDrawColor(220);
  doc.line(10, 44, W - 10, 44);

  // Info rows
  const rows = [
    ['Name', patientName],
    ['Email', maskedEmail],
    ['Department', department],
    ['Counter', counter],
    ['Position', position > 0 ? `${position}${ordinal(position)} in line` : '—'],
    ['Est. Wait', estimatedWait],
    ['Date', generatedDate],
    ['Time', generatedAt],
  ];

  doc.setFontSize(9);
  let y = 52;
  rows.forEach(([label, value]) => {
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(130);
    doc.text(label, 14, y);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(20);
    doc.text(String(value), 52, y);
    y += 7.5;
  });

  // ── QR code — use the one saved by generate-queue-form.js ──
  const savedQR = sessionStorage.getItem('lastQRDataURL');
  if (savedQR) {
    try {
      const qrSize = 32;
      doc.addImage(savedQR, 'PNG', (W - qrSize) / 2, y + 6, qrSize, qrSize);
      y += qrSize + 10;
      console.log('[PDF] QR added from sessionStorage');
    } catch (e) {
      console.warn('[PDF] QR embed failed:', e);
      y += 6;
    }
  } else {
    console.warn('[PDF] No QR in sessionStorage');
    y += 6;
  }

  // Footer
  doc.setDrawColor(220);
  doc.line(10, y + 2, W - 10, y + 2);
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(150);
  doc.text('Please stay nearby the waiting area and keep your phone on.', W / 2, y + 9, { align: 'center' });
  doc.text('You will be notified by email when it\'s your turn.', W / 2, y + 14, { align: 'center' });

  doc.save(`QueueCard-${queueNumber}.pdf`);
}

// ============================================================
// ORDINAL SUFFIX
// ============================================================
function ordinal(n) {
  if (!n || n === 0) return '';
  const s = ['th', 'st', 'nd', 'rd'];
  const v = n % 100;
  return s[(v - 20) % 10] || s[v] || s[0];
}

// ============================================================
// SOCKET.IO — live updates
// ============================================================
const socket = io();

socket.on('queue:update', (data) => {
  if (!currentData.queue_number || !data.queues) return;

  const updated = data.queues.find(q => q.queue_number === currentData.queue_number);
  if (!updated) return;

  updated.now_serving = data.now_serving ?? updated.now_serving;
  updated.estimated_wait = data.estimated_wait ?? updated.estimated_wait;

  currentData = { ...currentData, ...updated };
  renderStatus(currentData);

  if (currentData.status === 'Serving' || currentData.status === 'Completed') {
    almostNotified = true;
    stopAlmostTurnPolling();
  }
});

socket.on('queue:done', (data) => {
  if (data.queue_number !== currentData.queue_number) return;
  currentData = { ...currentData, status: 'Completed', position: 0 };
  renderStatus(currentData);
  almostNotified = true;
  stopAlmostTurnPolling();
});

// ============================================================
// ERROR SCREEN
// ============================================================
function showError(message) {
  document.getElementById('page-loader').hidden = true;
  const main = document.getElementById('main-content');
  if (!main) return;
  main.hidden = false;
  main.innerHTML = `
    <div style="text-align:center; padding: 3rem 1rem;">
      <p style="font-size:15px; color:#374151; font-weight:600; margin-bottom:.5rem;">Something went wrong</p>
      <p style="font-size:13px; color:#6B7280; margin-bottom:1.5rem;">${message}</p>
      <a href="/" style="font-size:13px; color:#0066FF;">← Back to Queue Generator</a>
    </div>
  `;
}